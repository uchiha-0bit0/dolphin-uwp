ControllerPreference GetWiiControllerPreference(std::string_view game_id)
{
  if (game_id.length() >= 4)
  {
    const std::string_view id4 = game_id.substr(0, 4);
    if (Contains(CLASSIC_IDS, id4))
      return ControllerPreference::Classic;
    if (Contains(GC_ONLY_IDS, id4))
      return ControllerPreference::GameCube;
  }

  if (game_id.length() >= 3)
  {
    const std::string_view id3 = game_id.substr(0, 3);
    if (Contains(CLASSIC_PREFIXES, id3))
      return ControllerPreference::Classic;
    if (Contains(GC_ONLY_PREFIXES, id3))
      return ControllerPreference::GameCube;
  }

  return ControllerPreference::WiiRemoteNunchuk;
}
